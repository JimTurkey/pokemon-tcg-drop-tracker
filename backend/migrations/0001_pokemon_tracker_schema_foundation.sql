CREATE TABLE pokemon_products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canonical_key TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  product_type TEXT NOT NULL,
  set_name TEXT,
  pack_count INTEGER,
  image_url TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pokemon_products_canonical_key_nonempty CHECK (BTRIM(canonical_key) <> ''),
  CONSTRAINT pokemon_products_name_nonempty CHECK (BTRIM(name) <> ''),
  CONSTRAINT pokemon_products_product_type_nonempty CHECK (BTRIM(product_type) <> ''),
  CONSTRAINT pokemon_products_pack_count_positive CHECK (pack_count IS NULL OR pack_count > 0),
  CONSTRAINT pokemon_products_metadata_object CHECK (JSONB_TYPEOF(metadata) = 'object')
);

CREATE INDEX idx_pokemon_products_active_type
  ON pokemon_products (product_type, canonical_key)
  WHERE active;

