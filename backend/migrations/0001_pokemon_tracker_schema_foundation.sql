CREATE TABLE value_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  calculation_key TEXT NOT NULL UNIQUE,
  pokemon_product_id BIGINT NOT NULL REFERENCES pokemon_products(id) ON DELETE RESTRICT,
  retailer_listing_id BIGINT REFERENCES retailer_listings(id) ON DELETE SET NULL,
  policy_version TEXT NOT NULL,
  rated BOOLEAN NOT NULL,
  unrated_reason TEXT,
  price NUMERIC(12, 2),
  pack_count INTEGER,
  price_per_pack NUMERIC(12, 4),
  value_score NUMERIC(5, 2),
  star_rating SMALLINT,
  value_tag TEXT,
  inputs JSONB NOT NULL DEFAULT '{}'::JSONB,
  calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT value_scores_key_nonempty CHECK (BTRIM(calculation_key) <> ''),
  CONSTRAINT value_scores_policy_nonempty CHECK (BTRIM(policy_version) <> ''),
  CONSTRAINT value_scores_price_nonnegative CHECK (price IS NULL OR price >= 0),
  CONSTRAINT value_scores_pack_count_positive CHECK (pack_count IS NULL OR pack_count > 0),
  CONSTRAINT value_scores_price_per_pack_nonnegative CHECK (price_per_pack IS NULL OR price_per_pack >= 0),
  CONSTRAINT value_scores_score_range CHECK (value_score IS NULL OR value_score BETWEEN 0 AND 100),
  CONSTRAINT value_scores_star_range CHECK (star_rating IS NULL OR star_rating BETWEEN 1 AND 5),
  CONSTRAINT value_scores_inputs_object CHECK (JSONB_TYPEOF(inputs) = 'object'),
  CONSTRAINT value_scores_rating_consistency CHECK (
    (
      rated
      AND unrated_reason IS NULL
      AND price IS NOT NULL
      AND pack_count IS NOT NULL
      AND price_per_pack IS NOT NULL
      AND value_score IS NOT NULL
      AND star_rating IS NOT NULL
      AND value_tag IS NOT NULL
    )
    OR
    (
      NOT rated
      AND unrated_reason IS NOT NULL
      AND value_score IS NULL
      AND star_rating IS NULL
      AND value_tag IS NULL
    )
  )
);

CREATE INDEX idx_value_scores_product_latest
  ON value_scores (pokemon_product_id, calculated_at DESC);

CREATE INDEX idx_value_scores_listing_latest
  ON value_scores (retailer_listing_id, calculated_at DESC);

CREATE INDEX idx_value_scores_rated_score_latest
  ON value_scores (value_score DESC, calculated_at DESC)
  WHERE rated;

